type PatternTranslation = {
  pattern: RegExp;
  ar: (...groups: string[]) => string;
  ru: (...groups: string[]) => string;
};

const INTERFACE_PATTERNS: PatternTranslation[] = [
  {
    pattern: /^Your Allocated Classes \((\d+)\)$/,
    ar: (count) => `الفصول المخصصة لك (${count})`,
    ru: (count) => `Назначенные вам классы (${count})`,
  },
  {
    pattern: /^(\d+) in progress$/,
    ar: (count) => `${count} قيد التنفيذ`,
    ru: (count) => `${count} в процессе`,
  },
  {
    pattern: /^Free plan — Lockdown mode only\. Upgrade to unlock Cambridge tests, IELTS, assignments & more\.$/,
    ar: () => 'الخطة المجانية — يتوفر وضع الحماية فقط. قم بالترقية لفتح اختبارات Cambridge وIELTS والواجبات والمزيد.',
    ru: () => 'Бесплатный тариф — доступен только режим Lockdown. Перейдите на другой тариф, чтобы открыть тесты Cambridge, IELTS, задания и другие функции.',
  },
  {
    pattern: /^Showing (\d+) of (\d+)$/,
    ar: (shown, total) => `عرض ${shown} من ${total}`,
    ru: (shown, total) => `Показано ${shown} из ${total}`,
  },
];

export function normalizeInterfaceSource(value: string): string {
  return value.trim().replace(/\s+/g, ' ');
}

export function translateInterfaceText(language: InterfaceLanguage, source: string): string {
  if (language === 'en') return source;
  const normalized = normalizeInterfaceSource(source);
  const exact = INTERFACE_MESSAGES[normalized];
  if (exact) return exact[language];
  for (const entry of INTERFACE_PATTERNS) {
    const match = normalized.match(entry.pattern);
    if (!match) continue;
    return entry[language](...match.slice(1));
  }
  return source;
}

export function hasInterfaceTranslation(source: string): boolean {
  const normalized = normalizeInterfaceSource(source);
  if (Boolean(INTERFACE_MESSAGES[normalized])) return true;
  return INTERFACE_PATTERNS.some((entry) => entry.pattern.test(normalized));
}
