const PATTERN_RULES: PatternRule[] = [
  {
    pattern: /^(\d[\d,]*) total assignments$/,
    translate: (language, match) => language === 'ar' ? `${match[1]} من إجمالي الواجبات` : `Всего заданий: ${match[1]}`,
  },
  {
    pattern: /^(\d[\d,]*) \/ (\d[\d,]*) answers correct$/,
    translate: (language, match) => language === 'ar' ? `${match[1]} من ${match[2]} إجابة صحيحة` : `${match[1]} из ${match[2]} ответов верны`,
  },
  {
    pattern: /^Leader • (\d+)\/(\d+) Agents Enlisted$/,
    translate: (language, match) => language === 'ar' ? `القائد • ${match[1]}/${match[2]} أعضاء منضمون` : `Лидер • ${match[1]}/${match[2]} участников`,
  },
  {
    pattern: /^CLAN LV\.(\d+)$/,
    translate: (language, match) => language === 'ar' ? `مستوى العشيرة ${match[1]}` : `КЛАН УР. ${match[1]}`,
  },
  {
    pattern: /^Welcome to (.+)$/,
    translate: (language, match) => language === 'ar' ? `مرحباً بك في ${match[1]}` : `Добро пожаловать в ${match[1]}`,
  },
  {
    pattern: /^(\d+) in progress$/,
    translate: (language, match) => language === 'ar' ? `${match[1]} قيد التنفيذ` : `В работе: ${match[1]}`,
  },
];

export function hasProfessionalInterfaceTranslation(value: string): boolean {
  return Boolean(PROFESSIONAL_MESSAGES[value]) || PATTERN_RULES.some((rule) => rule.pattern.test(value));
}

export function translateProfessionalInterfaceText(language: InterfaceLanguage, value: string): string | null {
  if (language === 'en') return value;
  const exact = PROFESSIONAL_MESSAGES[value]?.[language];
  if (exact) return exact;
  for (const rule of PATTERN_RULES) {
    const match = value.match(rule.pattern);
    if (match) return rule.translate(language, match);
  }
  return null;
}
