export function hasCompletionInterfaceTranslation(value: string): boolean {
  if (COMPLETION_MESSAGES[value]) return true;
  return DYNAMIC_RULES.some((rule) => rule.pattern.test(value));
}

export function translateCompletionInterfaceText(language: InterfaceLanguage, value: string): string | null {
  if (language === 'en') return value;
  const exact = COMPLETION_MESSAGES[value]?.[language];
  if (exact) return exact;
  for (const rule of DYNAMIC_RULES) {
    const match = value.match(rule.pattern);
    if (match) return rule.translate(language, match);
  }
  return null;
}
