create or replace function private.ielts_mock_cbt_can_take(p_code text) returns boolean
language sql stable security definer set search_path to '' as $$
  select auth.uid() is not null and exists(
    select 1 from private.ielts_mock_cbt_forms f join public.users u on u.id = auth.uid()
    where f.code = p_code and not coalesce(u.is_banned, false)
      and ((f.release_scope = 'pilot' and (auth.uid() = any(f.pilot_users) or public.is_superadmin(auth.uid())
              or exists(select 1 from private.ielts_course_batch_members m
                        join private.ielts_course_batches b on b.id = m.batch_id
                        where m.student_id = auth.uid() and m.left_at is null and b.id = any(f.release_batches)
                          and b.school_id = u.school_id and b.deleted_at is null and b.archived_at is null)))
        or (f.release_scope = 'full_access' and private.ielts_course_has_full_access())));
$$;
revoke all on function private.ielts_mock_cbt_can_take(text) from public, anon, authenticated;

-- Each linked Writing script with its review state (the band only once the teacher has finalized the review).
create or replace function private.ielts_mock_cbt_writing_status(p_attempt uuid) returns jsonb
language sql stable security definer set search_path to '' as $$
  select coalesce(jsonb_agg(jsonb_build_object(
      'task', l.task_key, 'label', l.label, 'writing_attempt_id', l.writing_attempt_id,
      'reviewed', coalesce(r.finalized, false),
      'band', case when r.finalized then r.overall_band end,
      'reviewed_at', case when r.finalized then r.reviewed_at end) order by l.task_key), '[]'::jsonb)
  from private.ielts_mock_cbt_writing_links l
  left join public.ielts_productive_skill_reviews r on r.attempt_type = 'writing' and r.attempt_id = l.writing_attempt_id::text
  where l.mock_attempt_id = p_attempt;
$$;
revoke all on function private.ielts_mock_cbt_writing_status(uuid) from public, anon, authenticated;

-- The teacher's finalized criterion bands of a computer attempt's linked scripts, in the mock criteria shape
-- ({t1:{ta,cc,lr,gra}, t2:{tr,cc,lr,gra}}), with how many linked scripts are still open. Null when nothing is linked.
create or replace function private.ielts_mock_cbt_linked_criteria(p_attempt uuid) returns jsonb
language sql stable security definer set search_path to '' as $$
  with x as (
    select l.task_key, coalesce(r.finalized, false) fin, r.rubric
    from private.ielts_mock_cbt_writing_links l
    left join public.ielts_productive_skill_reviews r on r.attempt_type = 'writing' and r.attempt_id = l.writing_attempt_id::text
    where l.mock_attempt_id = p_attempt)
  select case when not exists(select 1 from x) then null else jsonb_build_object(
    'open', (select count(*) from x where not fin),
    'criteria', jsonb_strip_nulls(jsonb_build_object(
      't1', (select jsonb_build_object('ta', rubric -> 'task_achievement', 'cc', rubric -> 'coherence_cohesion', 'lr', rubric -> 'lexical_resource', 'gra', rubric -> 'grammar') from x where task_key = 't1' and fin),
      't2', (select jsonb_build_object('tr', rubric -> 'task_achievement', 'cc', rubric -> 'coherence_cohesion', 'lr', rubric -> 'lexical_resource', 'gra', rubric -> 'grammar') from x where task_key = 't2' and fin)))) end;
$$;
revoke all on function private.ielts_mock_cbt_linked_criteria(uuid) from public, anon, authenticated;

-- What happened during the Writing section, for the teacher: never a score and never shown to the student.
create or replace function private.ielts_mock_cbt_integrity(p_attempt uuid) returns jsonb
language sql stable security definer set search_path to '' as $$
  select jsonb_build_object(
    'tab_switches', (select count(*) from private.ielts_mock_cbt_events e where e.attempt_id = a.id and e.kind = 'tab_hidden'),
    'focus_lost', (select count(*) from private.ielts_mock_cbt_events e where e.attempt_id = a.id and e.kind = 'window_blur'),
    'paste_blocked', (select count(*) from private.ielts_mock_cbt_events e where e.attempt_id = a.id and e.kind in ('paste_blocked', 'drop_blocked')),
    'minutes_used', round(extract(epoch from ((a.sections -> 'writing' ->> 'closed_at')::timestamptz
                                            - (a.sections -> 'writing' ->> 'started_at')::timestamptz)) / 60),
    'closed_by', a.sections -> 'writing' ->> 'closed_by',
    'started_at', a.sections -> 'writing' ->> 'started_at')
  from private.ielts_mock_cbt_attempts a where a.id = p_attempt;
$$;
revoke all on function private.ielts_mock_cbt_integrity(uuid) from public, anon, authenticated;

-- Turn the closed Writing section of a form with review tasks into Writing scripts for the ordinary review. Idempotent.
create or replace function private.ielts_mock_cbt_route_writing(p_attempt uuid) returns void
language plpgsql security definer set search_path to '' as $$
declare t private.ielts_mock_cbt_attempts; rt private.ielts_mock_cbt_review_tasks; v_text text; v_id uuid;
begin
  select * into t from private.ielts_mock_cbt_attempts where id = p_attempt;
  if t.id is null then return; end if;
  for rt in select * from private.ielts_mock_cbt_review_tasks where code = t.mock_code order by task_key loop
    if exists(select 1 from private.ielts_mock_cbt_writing_links where mock_attempt_id = t.id and task_key = rt.task_key) then continue; end if;
    v_text := t.answers -> 'writing' ->> rt.task_key;
    -- A blank task has nothing to review (the Writing table refuses blank essays); the attempt still records it.
    if length(btrim(coalesce(v_text, ''))) = 0 then continue; end if;
    insert into public.ielts_writing_attempts(user_id, task_id, submitted_at, answer_text, word_count)
    values (t.student_id, rt.writing_task_id, coalesce(t.completed_at, now()), v_text, private.ielts_mock_cbt_words(v_text))
    returning id into v_id;
    insert into private.ielts_mock_cbt_writing_links(mock_attempt_id, task_key, mock_code, writing_attempt_id, label, fresh)
    values (t.id, rt.task_key, t.mock_code, v_id, case when t.exposed then rt.label else rt.fresh_label end, not t.exposed);
  end loop;
end $$;
revoke all on function private.ielts_mock_cbt_route_writing(uuid) from public, anon, authenticated;

-- Close the current section: mark Listening/Reading, move to the form's next section, and route Writing for review.
create or replace function private.ielts_mock_cbt_close_section(p_attempt uuid, p_reason text) returns void
language plpgsql security definer set search_path to '' as $$
declare t private.ielts_mock_cbt_attempts; f private.ielts_mock_cbt_forms; s jsonb; nxt text; secs text[];
begin
  select * into t from private.ielts_mock_cbt_attempts where id = p_attempt for update;
  if t.status <> 'in_progress' or t.section = 'done' then return; end if;
  select * into f from private.ielts_mock_cbt_forms where code = t.mock_code;
  if t.section in ('listening', 'reading') then
    s := private.ielts_mock_cbt_score(f.answer_key -> t.section, coalesce(t.answers -> t.section, '{}'::jsonb));
    insert into private.ielts_mock_cbt_scores(attempt_id, section, raw, outcomes)
    values (t.id, t.section, (s ->> 'raw')::int, s -> 'outcomes')
    on conflict (attempt_id, section, scoring_policy) do nothing;
  end if;
  secs := private.ielts_mock_cbt_sections(f);
  nxt := coalesce(secs[array_position(secs, t.section) + 1], 'done');
  update private.ielts_mock_cbt_attempts set
    sections = sections || jsonb_build_object(t.section, jsonb_build_object(
      'started_at', t.section_started_at, 'deadline', t.section_deadline, 'closed_at', now(), 'closed_by', p_reason)),
    section = nxt, section_started_at = null, section_deadline = null,
    status = case when nxt = 'done' then 'completed' else status end,
    completed_at = case when nxt = 'done' then now() else completed_at end
  where id = t.id;
  if t.section = 'writing' then perform private.ielts_mock_cbt_route_writing(t.id); end if;
end $$;
revoke all on function private.ielts_mock_cbt_close_section(uuid, text) from public, anon, authenticated;

-- 6. Learner RPCs.
create or replace function public.rpc_ielts_mock_cbt_home() returns jsonb
language plpgsql volatile security definer set search_path to '' as $$
declare v_actor uuid := auth.uid();
begin
  if v_actor is null then raise exception using errcode = '42501', message = 'not_authenticated'; end if;
  return coalesce((select jsonb_agg(jsonb_build_object(
      'code', f.code, 'title', private.ielts_mock_cbt_title(f, pr.practice), 'version', f.version,
      'kind', private.ielts_mock_cbt_kind(f, pr.practice), 'sections', to_jsonb(private.ielts_mock_cbt_sections(f)),
      'practice', pr.practice,
      'available', private.ielts_mock_cbt_can_take(f.code) and private.ielts_mock_cbt_attempts_left(f, v_actor),
      'minutes', (select round(sum(extract(epoch from private.ielts_mock_cbt_duration(f, x))) / 60)
                  from unnest(private.ielts_mock_cbt_sections(f)) x),
      'attempts', (select coalesce(jsonb_agg(jsonb_build_object(
          'id', a.id, 'status', a.status, 'section', a.section, 'attempt_no', a.attempt_no, 'practice', a.exposed,
          'started_at', a.started_at, 'completed_at', a.completed_at,
          'listening', (select s.raw from private.ielts_mock_cbt_scores s where s.attempt_id = a.id and s.section = 'listening'),
          'reading', (select s.raw from private.ielts_mock_cbt_scores s where s.attempt_id = a.id and s.section = 'reading'),
          'writing_reviewed', exists(select 1 from private.ielts_mock_cbt_writing_reviews w where w.attempt_id = a.id)
            or (exists(select 1 from private.ielts_mock_cbt_writing_links l where l.mock_attempt_id = a.id)
                and not exists(select 1 from private.ielts_mock_cbt_writing_links l
                               left join public.ielts_productive_skill_reviews r on r.attempt_type = 'writing' and r.attempt_id = l.writing_attempt_id::text
                               where l.mock_attempt_id = a.id and not coalesce(r.finalized, false))),
          'writing_tasks', private.ielts_mock_cbt_writing_status(a.id))
          order by a.started_at desc), '[]'::jsonb)
        from private.ielts_mock_cbt_attempts a where a.student_id = v_actor and a.mock_code = f.code))
    order by f.code)
    from private.ielts_mock_cbt_forms f
    -- Whether a new or the latest attempt is practice for this student (a rewrite of a mock they already sat).
    cross join lateral (select coalesce((select a.exposed from private.ielts_mock_cbt_attempts a where a.student_id = v_actor and a.mock_code = f.code
                                         order by a.started_at desc limit 1), private.ielts_mock_cbt_seen_rewrite(f, v_actor)) practice) pr
    where private.ielts_mock_cbt_can_take(f.code)
       or exists(select 1 from private.ielts_mock_cbt_attempts a where a.student_id = v_actor and a.mock_code = f.code)), '[]'::jsonb);
end $$;
revoke all on function public.rpc_ielts_mock_cbt_home() from public, anon;
grant execute on function public.rpc_ielts_mock_cbt_home() to authenticated;

-- A rewrite is practice for a student who already sat the mock it rewrites, and a first sitting for everyone else; a
-- form may limit attempts; the first section comes from the form.
create or replace function public.rpc_ielts_mock_cbt_start(p_code text) returns jsonb
language plpgsql volatile security definer set search_path to '' as $$
declare v_actor uuid := auth.uid(); f private.ielts_mock_cbt_forms; v_id uuid; v_no int;
begin
  if v_actor is null then raise exception using errcode = '42501', message = 'not_authenticated'; end if;
  select id into v_id from private.ielts_mock_cbt_attempts where student_id = v_actor and mock_code = p_code and status = 'in_progress';
  if v_id is not null then return jsonb_build_object('attempt_id', v_id, 'resumed', true); end if;
  if not private.ielts_mock_cbt_can_take(p_code) then raise exception using errcode = '42501', message = 'mock_not_available'; end if;
  select * into f from private.ielts_mock_cbt_forms where code = p_code;
  perform pg_advisory_xact_lock(hashtext('ielts_mock_cbt:' || v_actor::text || ':' || p_code));
  select id into v_id from private.ielts_mock_cbt_attempts where student_id = v_actor and mock_code = p_code and status = 'in_progress';
  if v_id is not null then return jsonb_build_object('attempt_id', v_id, 'resumed', true); end if;
  if not private.ielts_mock_cbt_attempts_left(f, v_actor) then raise exception using errcode = '42501', message = 'mock_attempts_used'; end if;
  select coalesce(max(attempt_no), 0) + 1 into v_no from private.ielts_mock_cbt_attempts where student_id = v_actor and mock_code = p_code;
  insert into private.ielts_mock_cbt_attempts(student_id, mock_code, form_version, content_sha256, attempt_no, exposed, section)
  values (v_actor, f.code, f.version, f.content_sha256, v_no,
          v_no > 1 or private.ielts_mock_cbt_seen_rewrite(f, v_actor) or private.ielts_mock_cbt_seen_before(v_actor, f.code, now()),
          (private.ielts_mock_cbt_sections(f))[1])
  returning id into v_id;
  return jsonb_build_object('attempt_id', v_id, 'resumed', false);
end $$;
revoke all on function public.rpc_ielts_mock_cbt_start(text) from public, anon;
grant execute on function public.rpc_ielts_mock_cbt_start(text) to authenticated;

create or replace function public.rpc_ielts_mock_cbt_state(p_attempt uuid) returns jsonb
language plpgsql volatile security definer set search_path to '' as $$
declare t private.ielts_mock_cbt_attempts; f private.ielts_mock_cbt_forms; v_payload jsonb;
begin
  t := private.ielts_mock_cbt_own_attempt(p_attempt);
  select * into f from private.ielts_mock_cbt_forms where code = t.mock_code;
  if t.section in ('listening', 'reading', 'writing') and t.section_started_at is not null then
    v_payload := f.payload -> t.section;
  end if;
  return jsonb_build_object(
    'attempt_id', t.id, 'code', t.mock_code, 'title', private.ielts_mock_cbt_title(f, t.exposed), 'version', t.form_version,
    'kind', private.ielts_mock_cbt_kind(f, t.exposed), 'sections', to_jsonb(private.ielts_mock_cbt_sections(f)),
    'status', t.status, 'section', t.section, 'practice', t.exposed, 'attempt_no', t.attempt_no,
    'started', t.section_started_at is not null, 'section_started_at', t.section_started_at,
    'deadline', t.section_deadline, 'server_now', now(),
    'remaining_seconds', case when t.section_deadline is null then null else greatest(0, extract(epoch from (t.section_deadline - now())))::int end,
    'section_seconds', case when t.section in ('listening', 'reading', 'writing') then extract(epoch from private.ielts_mock_cbt_duration(f, t.section))::int end,
    'audio', case when t.section = 'listening' then jsonb_build_object('url', f.audio ->> 'url', 'listen_end', (f.audio ->> 'listen_end')::numeric,
      'sample_end', (f.audio ->> 'sample_end')::numeric, 'review_seconds', (f.timing ->> 'listening_review_seconds')::int,
      'elapsed', case when t.section_started_at is null then null else extract(epoch from (now() - t.section_started_at)) end) end,
    'payload', v_payload,
    'answers', case when v_payload is null then null else coalesce(t.answers -> t.section, '{}'::jsonb) end,
    'saved_at', t.saved_at);
end $$;
revoke all on function public.rpc_ielts_mock_cbt_state(uuid) from public, anon;
grant execute on function public.rpc_ielts_mock_cbt_state(uuid) to authenticated;

-- Integrity events for the learner's own open section. Bounded per attempt; never blocks the test.
create or replace function public.rpc_ielts_mock_cbt_log_event(p_attempt uuid, p_kind text) returns jsonb
language plpgsql volatile security definer set search_path to '' as $$
declare t private.ielts_mock_cbt_attempts;
begin
  if p_kind is null or p_kind not in ('tab_hidden', 'tab_visible', 'window_blur', 'paste_blocked', 'drop_blocked') then
