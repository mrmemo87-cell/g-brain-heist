#!/usr/bin/env python3
"""Build the install migration for a practice-bank batch: one call to private.ielts_install_practice_bank with the
batch document (Diagnostic Bible 2.0.0 section 15E.2A). Usage: build-practice-bank-sql.py batch.json out.sql"""
import json, sys
src, out = sys.argv[1], sys.argv[2]
doc = json.dumps(json.load(open(src)), separators=(',', ':'), ensure_ascii=False)
tag = '$bank$'
assert tag not in doc
open(out, 'w').write(f"-- Install {json.loads(doc)['batch']} from docs/ielts/practice-bank/{src.split('/')[-1]} as unavailable drafts with proposed mappings.\n"
                     f"-- Generated by scripts/ielts/build-practice-bank-sql.py; review happens in Content manager -> Practice bank review.\n"
                     f"select private.ielts_install_practice_bank({tag}{doc}{tag}::jsonb);\n")
